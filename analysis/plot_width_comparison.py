def main() -> None:
    runs = wc.load_all()
    wc.check_comparable(runs)  # raises ValidationError on any inconsistency
    plt.rcParams.update({"font.size": 11, "axes.spines.top": False, "axes.spines.right": False})

    # ---------------------------------------------------------------- aggregates
    agg = {n: wc.aggregate_periodic([r.periodic for r in rs]) for n, rs in runs.items()}
    out_agg = pd.DataFrame({"step": agg[BASE]["step"]})
    for n in runs:
        out_agg[f"{n}_mean"], out_agg[f"{n}_sd"] = agg[n]["mean"], agg[n]["sd"]
        for r in runs[n]:
            out_agg[f"{n}_seed{r.seed}"] = r.periodic["mean_return"].to_numpy()
    OUT.mkdir(parents=True, exist_ok=True)
    out_agg.to_csv(OUT / "width_comparison_periodic_aggregate.csv", index=False)

    # ---------------------------------------------------------------- per-run table
    rows = []
    for n, rs in runs.items():
        for r in rs:
            spikes = wc.critic_loss_spikes(r.train["critic_loss"], SMOOTH)
            rows.append({
                "architecture": r.spec.label, "seed": r.seed, "run_id": r.config["run_id"],
                "git_commit": r.meta["git_commit"], "git_dirty": r.meta["git_dirty"],
                "hidden_width": r.hidden_width, "total_params": r.meta["parameter_counts"]["total"],
                "final_mean_return_10ep": r.final_mean_return,
                "final_within_seed_episode_sd": float(r.final["std_return"]),
                "periodic_mean_return_1M_5ep": float(r.periodic["mean_return"].iloc[-1]),
                "auc_mean_of_40_periodic": float(r.periodic["mean_return"].mean()),
                "steps_to_5000": wc.steps_to_threshold(r.periodic, 5000),
                "steps_to_8000": wc.steps_to_threshold(r.periodic, 8000),
                "steps_to_10000": wc.steps_to_threshold(r.periodic, 10000),
                "late_eval_sd_750k_1M": float(r.periodic[r.periodic["step"] >= 750_000]["mean_return"].std(ddof=1)),
                "max_drawdown_periodic": wc.max_drawdown(r.periodic),
                "low_return_outlier_evals_total": wc.count_low_return_outlier_evals(r.periodic),
                "low_return_outlier_evals_after_500k": wc.count_low_return_outlier_evals(r.periodic, 500_000),
                "critic_loss_spikes_10x_median": spikes["n_spikes"],
                "critic_loss_spike_steps": ";".join(str(int(r.train["step"].iloc[i])) for i in spikes["event_positions"]),
                "critic_loss_max_ratio_to_median": spikes["max_ratio"],
                "critic_loss_max": float(r.train["critic_loss"].max()),
                "critic_loss_median": float(r.train["critic_loss"].median()),
                "runtime_hours": r.runtime_hours,
                "final_cumulative_sps": float(r.train["sps"].iloc[-1]),
            })
    per_run = pd.DataFrame(rows)
    per_run.to_csv(OUT / "width_comparison_per_run.csv", index=False)

    # ---------------------------------------------------------------- stats
    def col(arch_label, c):
        return per_run[per_run["architecture"] == arch_label][c].to_numpy(dtype=float)

    lb, lw_ = label(runs, BASE), label(runs, WIDE)
    stats = {"seeds": list(wc.SEEDS), "n_per_architecture": 3, "sd_definition": "sample SD, ddof=1, across training seeds"}
    for metric in ("final_mean_return_10ep", "periodic_mean_return_1M_5ep", "auc_mean_of_40_periodic",
                   "late_eval_sd_750k_1M", "max_drawdown_periodic", "low_return_outlier_evals_after_500k", "runtime_hours", "final_cumulative_sps",
                   "critic_loss_spikes_10x_median"):
        a, b = col(lb, metric), col(lw_, metric)
        stats[metric] = {
            lb: {"mean": wc.mean_sd(a)[0], "sd": wc.mean_sd(a)[1], "per_seed": a.tolist()},
            lw_: {"mean": wc.mean_sd(b)[0], "sd": wc.mean_sd(b)[1], "per_seed": b.tolist()},
            "effect_width_vs_baseline": wc.effect_size(a, b),
        }
    stats["steps_to_threshold"] = {
        str(t): {lbl: col(lbl, f"steps_to_{t}").tolist() for lbl in (lb, lw_)} for t in THRESHOLDS}
    runtimes = {f"{r.spec.label} seed {r.seed}": r.runtime_hours for rs in runs.values() for r in rs}
    stats["runtime_hours_by_run"] = runtimes
    stats["runtime_flagged_slow_(>1.5x_median_of_six)"] = wc.flag_slow_runs(runtimes, 1.5)
    stats["runtime_median_excluding_flagged"] = {
        lbl: float(np.median([v for k, v in runtimes.items() if k.startswith(lbl) and k not in stats["runtime_flagged_slow_(>1.5x_median_of_six)"]]))
        for lbl in (lb, lw_)}
    (OUT / "width_comparison_stats.json").write_text(wc.dumps_strict(stats), encoding="utf-8")

    # ---------------------------------------------------------------- checkpoint table
    diag = (("critic_loss", "critic_loss"), ("alpha", "alpha"), ("q_mean_abs", "q_mean_abs"),
            ("critic_grad_norm", "critic_grad_norm"))
    ck_rows = []
    for cp in CHECKPOINTS:
        i = int(np.where(agg[BASE]["step"].to_numpy() == cp)[0][0])
        for n, rs in runs.items():
            row = {"step": cp, "architecture": label(runs, n),
                   "eval_return_mean": agg[n]["mean"][i], "eval_return_sd_between_seeds": agg[n]["sd"][i]}
            for c, _ in diag:
                vals = [wc.window_mean(r.train, c, cp) for r in rs]
                row[f"{c}_window_mean"], row[f"{c}_window_sd_between_seeds"] = wc.mean_sd(vals)
            ck_rows.append(row)
    ck = pd.DataFrame(ck_rows)
    ck.to_csv(OUT / "width_comparison_checkpoints.csv", index=False)

    # ---------------------------------------------------------------- figures
    # 1. learning curves: per-seed (thin) + architecture mean +/- 1 sample SD
    fig, axes = plt.subplots(1, 2, figsize=(14, 5.6), sharey=True)
    for n in runs:
        steps, mu, sd = agg[n]["step"], agg[n]["mean"], agg[n]["sd"]
        axes[0].plot(steps, mu, color=COLORS[n], lw=2.2, label=f"{label(runs, n)} mean (n=3)")
        axes[0].fill_between(steps, mu - sd, mu + sd, color=COLORS[n], alpha=0.2)
        for r in runs[n]:
            axes[1].plot(r.periodic["step"], r.periodic["mean_return"], color=COLORS[n], lw=1.2,
                         alpha=0.85, ls=("-", "--", ":")[r.seed], label=f"{label(runs, n)} seed {r.seed}")
    axes[0].set_title("Mean ± 1 between-seed sample SD")
    axes[1].set_title("Individual seeds")
    for ax in axes:
        style(ax, "Mean return over 5 evaluation episodes")
        ax.legend(fontsize=9)
    fig.suptitle("SAC on HalfCheetah-v5: 2×256 vs 2×512 deterministic-evaluation learning curves")
    save(fig, "01_learning_curves_comparison")

    # 2. final returns (separate 10-episode final evaluation)
    fig, ax = plt.subplots(figsize=(7.5, 5.6))
    for k, n in enumerate(runs):
        vals = col(label(runs, n), "final_mean_return_10ep")
        m, s = wc.mean_sd(vals)
        for r, v in zip(runs[n], vals):
            ax.scatter(k + (r.seed - 1) * 0.08, v, color=COLORS[n], marker=MARKERS[r.seed], s=70, zorder=3,
                       label=f"seed {r.seed}" if k == 0 else None)
        ax.errorbar(k + 0.3, m, yerr=s, color="black", marker="D", capsize=5, lw=1.6, zorder=4,
                    label="mean ± sample SD (n=3)" if k == 0 else None)
        ax.annotate(f"{m:,.0f} ± {s:,.0f}", (k + 0.3, m + s), textcoords="offset points", xytext=(0, 8),
                    ha="center", fontsize=9)
    ax.set_xticks(range(len(runs)), [label(runs, n) for n in runs])
    ax.set_ylabel("Final return (10 deterministic episodes)")
    ax.set_title("Final performance by seed (SD = between training seeds)")
    ax.grid(alpha=0.22, axis="y")
    ax.legend(fontsize=9, loc="upper center", bbox_to_anchor=(0.5, -0.08), ncol=2, frameon=False)
    save(fig, "02_final_returns")

    # 3. throughput / runtime (observed; GPU contention was not recorded in the logs)
    fig, axes = plt.subplots(1, 2, figsize=(14, 5.6))
    for n, rs in runs.items():
        for r in rs:
            axes[0].plot(r.train["step"], r.train["sps"], color=COLORS[n], lw=1.3,
                         ls=("-", "--", ":")[r.seed], label=f"{label(runs, n)} seed {r.seed}")
    style(axes[0], "Cumulative environment steps per second")
    axes[0].set_title("Observed cumulative throughput")
    axes[0].legend(ncol=2, fontsize=9)
    names = list(runtimes)
    flagged = set(stats["runtime_flagged_slow_(>1.5x_median_of_six)"])
    bar_colors = [COLORS[BASE] if k.startswith(lb) else COLORS[WIDE] for k in names]
    bars = axes[1].bar(range(len(names)), [runtimes[k] for k in names], color=bar_colors,
                       hatch=None)
    for b, k in zip(bars, names):
        if k in flagged:
            b.set_hatch("//")
    axes[1].set_xticks(range(len(names)), [k.replace(" seed ", "\nseed ") for k in names], fontsize=9)
    axes[1].set_ylabel("Wall-clock runtime (hours)")
    axes[1].set_title("Runtime per run (hatched = >1.5× median of six runs;\nshared-GPU load not recorded)")
    axes[1].grid(alpha=0.22, axis="y")
    save(fig, "03_throughput_and_runtime")

    # 4. critic loss, 5. alpha, 6. |Q| and critic gradients
    per_seed_diag_figure(runs, "critic_loss", "Critic loss (log scale)", "04_critic_loss",
                         "Critic loss", logy=True)
